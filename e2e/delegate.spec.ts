import { test, expect } from "@playwright/test";

// GOV.UK Delegate on its own: consent through the real One Login simulator,
// then the account page. The agent and HMRC have their own specs.

const DELEGATE = process.env.DELEGATE_URL ?? "http://localhost:3300";
const CLIENT_ID = process.env.DEMO_AGENT_CLIENT_ID ?? "demo-personal-agent";
const CLIENT_SECRET = process.env.DEMO_AGENT_CLIENT_SECRET ?? "dev-demo-agent-secret";

async function createRequest() {
  const tok = await (await fetch(`${DELEGATE}/api/agent/token`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ client_id: CLIENT_ID, client_secret: CLIENT_SECRET }),
  })).json();
  const res = await fetch(`${DELEGATE}/api/authorisation-requests`, {
    method: "POST",
    headers: { "content-type": "application/json", authorization: `Bearer ${tok.access_token}` },
    body: JSON.stringify({ service: "hmrc-personal-tax", capabilities: ["view_tax_code", "claim_job_expenses", "update_employment"] }),
  });
  return (await res.json()) as { id: string; consent_url: string };
}

test("consent: sign in with One Login, narrow the request, allow; then remove access from the account page", async ({ page }) => {
  const req = await createRequest();

  await page.goto(req.consent_url);
  await expect(page.getByRole("heading", { name: "Sign in with GOV.UK One Login" })).toBeVisible();
  await page.getByRole("button", { name: "Continue to sign in" }).click();
  await expect(page).toHaveURL(/localhost:3301\/authorize/);
  await page.getByRole("button", { name: /continue/i }).click();

  await expect(page.getByRole("heading", { level: 1, name: "Example AI assistant wants to act for you" })).toBeVisible();
  await page.getByLabel(/Update your employment details/).uncheck();
  await page.getByRole("button", { name: "Continue" }).click();
  await expect(page.getByRole("heading", { name: "Check what you are allowing" })).toBeVisible();
  await expect(page.getByText("Not allowed to")).toBeVisible();
  await page.getByRole("button", { name: "Allow" }).click();
  await expect(page.getByRole("heading", { name: "Agent authorised" })).toBeVisible();

  await page.goto("/account/delegates");
  await expect(page.getByRole("heading", { name: "Who can act for you" })).toBeVisible();
  await page.getByRole("link", { name: /Remove access/ }).first().click();
  await page.getByRole("button", { name: "Remove access" }).click();
  await expect(page.getByRole("heading", { name: "Access removed" })).toBeVisible();

  await page.goto("/activity");
  await expect(page.getByRole("heading", { name: "Declared agent activity" })).toBeVisible();
});

test("front door names the four systems and what each had to add", async ({ page }) => {
  await page.goto("/");
  for (const name of ["GOV.UK One Login", "GOV.UK Delegate", /HMRC/, "Example AI"]) {
    await expect(page.locator("table.systems-table").getByRole("rowheader", { name })).toBeVisible();
  }
  await expect(page.getByText("legitimate automation easier than illegitimate automation")).toBeVisible();
});

test("about page explains the proposition", async ({ page }) => {
  await page.goto("/about");
  await expect(page.getByRole("heading", { name: "What each system had to add" })).toBeVisible();
  await expect(page.getByText("does not detect whether text was generated by AI")).toBeVisible();
});

test("keyboard: skip link is first focusable", async ({ page }) => {
  await page.goto("/");
  await page.keyboard.press("Tab");
  await expect(page.getByRole("link", { name: "Skip to main content" })).toBeFocused();
});

test("reflow at 320px: no horizontal page scroll", async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 700 });
  for (const path of ["/", "/about", "/activity", "/consent-signin"]) {
    await page.goto(path);
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
    expect(overflow, `${path} overflows horizontally`).toBeLessThanOrEqual(0);
  }
});
